#!/usr/bin/env python3
"""Writes app/lib/core/date_data.dart: Flutter's date data for Amharic and
English only.

intl's DateFormat needs each language's month and day names and patterns.
Flutter's flutter_localizations has them for every language it supports (as
does intl), which the web app would download for nothing; the app registers
its two languages from this copy instead (app/lib/core/localizations.dart).

Run it after a Flutter upgrade, with the Flutter SDK's path:

    python pipeline/build_dart_dates.py C:/src/flutter
"""
from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / 'app' / 'lib' / 'core' / 'date_data.dart'
LOCALES = ('am', 'en')
SOURCE = 'packages/flutter_localizations/lib/src/l10n/generated_date_localizations.dart'


def block(lines: list[str], start: str, end: str) -> list[str]:
    """The lines from the one starting with [start] to the next one equal to [end]."""
    first = next(i for i, line in enumerate(lines) if line.startswith(start))
    last = next(i for i in range(first + 1, len(lines)) if lines[i] == end)
    return lines[first:last + 1]


def dart_source(flutter_sdk: Path) -> str:
    lines = (flutter_sdk / SOURCE).read_text(encoding='utf-8').split('\n')
    symbols, patterns = [], []
    for locale in LOCALES:
        symbols += block(lines, f"  '{locale}': intl.DateSymbols(", '  ),')
        patterns += block(lines, f"  '{locale}': <String, String>{{", '  },')
    return '\n'.join([
        "// Date names and formats in the app's two languages, for intl's DateFormat:",
        "// the app's own dates, and the date and time texts of Flutter's widgets.",
        '//',
        "// Generated by pipeline/build_dart_dates.py from Flutter's flutter_localizations",
        '// (lib/src/l10n/generated_date_localizations.dart, from CLDR data), for',
        "// Amharic and English only: Flutter's copy, like intl's, holds every language",
        '// Flutter supports, which the web app would download for nothing. Do not edit.',
        '//',
        '// Copyright 2014 The Flutter Authors. All rights reserved.',
        '// Use of this source code is governed by a BSD-style license that can be',
        '// found in the LICENSE file of the Flutter SDK.',
        '',
        "import 'package:intl/date_symbol_data_custom.dart';",
        "import 'package:intl/date_symbols.dart' as intl;",
        '',
        'final _symbols = <String, intl.DateSymbols>{',
        *symbols,
        '};',
        '',
        'const _patterns = <String, Map<String, String>>{',
        *patterns,
        '};',
        '',
        'var _initialized = false;',
        '',
        '/// Registers Amharic and English dates with intl, once.',
        'void initializeAppDateFormatting() {',
        '  if (_initialized) return;',
        '  _symbols.forEach(',
        '    (locale, symbols) => initializeDateFormattingCustom(locale: locale, symbols: symbols, patterns: _patterns[locale]),',
        '  );',
        '  _initialized = true;',
        '}',
        '',
    ])


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print(__doc__)
        return 2
    OUT.write_text(dart_source(Path(argv[0])), encoding='utf-8', newline='\n')
    # Flutter's file is wrapped for its own line width; CI checks the app's.
    dart = shutil.which('dart')
    if dart:
        subprocess.run([dart, 'format', str(OUT)], check=True, capture_output=True)
        print(f'wrote and formatted {OUT}')
    else:
        print(f'wrote {OUT}; run `dart format` on it (in app/) before committing')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
