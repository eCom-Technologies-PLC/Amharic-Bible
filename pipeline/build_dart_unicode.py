#!/usr/bin/env python3
"""Writes app/lib/core/unicode_data.dart: the Unicode data the app's search
normalization needs, from Python's unicodedata.

The pipeline normalizes text for the search index with unicodedata (canonical
decomposition, then dropping nonspacing marks: abible/geez.py's normalize), and
the app normalizes what readers type the same way (app/lib/core/geez.dart). A
Dart Unicode package would be about 300 KB of the web app's code, most of it
for normalizations search doesn't use; this table is a tenth of that.

Run it after upgrading Python to a newer Unicode version (the table may only
grow: canonical decompositions never change once assigned):

    python pipeline/build_dart_unicode.py

tests/test_dart_unicode.py checks the written table against unicodedata.
"""
from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / 'app' / 'lib' / 'core' / 'unicode_data.dart'

# Hangul syllables decompose by formula (the app computes them).
HANGUL = range(0xAC00, 0xD7A4)


def decompositions() -> dict[int, str]:
    """Each character whose canonical decomposition differs from it, Hangul
    syllables aside, mapped to that decomposition without nonspacing marks
    (category Mn): what search keeps of it."""
    table = {}
    for cp in range(0x110000):
        if cp in HANGUL or 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        nfd = unicodedata.normalize('NFD', ch)
        if nfd != ch:
            table[cp] = ''.join(c for c in nfd if unicodedata.category(c) != 'Mn')
    return table


def encode(table: dict[int, str]) -> str:
    """Entries in code point order, separated by dots: the code point, then
    each character it decomposes to, as five hex digits."""
    return '.'.join(f'{cp:05X}' + ''.join(f'{ord(c):05X}' for c in table[cp]) for cp in sorted(table))


def decode(text: str) -> dict[int, str]:
    table = {}
    for entry in text.split('.'):
        codes = [int(entry[i:i + 5], 16) for i in range(0, len(entry), 5)]
        table[codes[0]] = ''.join(chr(c) for c in codes[1:])
    return table


def dart_source(table: dict[int, str]) -> str:
    data = encode(table)
    # Long string split into adjacent literals, a line each.
    lines = [data[i:i + 110] for i in range(0, len(data), 110)]
    literal = '\n'.join(f"    '{line}'" for line in lines)
    return f"""// Generated by pipeline/build_dart_unicode.py from Unicode {unicodedata.unidata_version} (Python's
// unicodedata). Do not edit.

/// The Unicode version of [decompositionTable].
const unicodeVersion = '{unicodedata.unidata_version}';

/// Each character with a canonical decomposition, Hangul syllables aside (they
/// decompose by formula), with that decomposition minus nonspacing marks: in
/// code point order, entries separated by dots, each the code point and then
/// the characters it decomposes to, as five hex digits ({len(table)} entries).
const decompositionTable =
{literal};
"""


def main() -> int:
    table = decompositions()
    OUT.write_text(dart_source(table), encoding='utf-8', newline='\n')
    print(f'wrote {OUT} ({len(table)} decompositions, Unicode {unicodedata.unidata_version})')
    return 0


if __name__ == '__main__':
    sys.exit(main())
